#ifndef LLVM_LIB_TARGET_GPUVM_MCTARGETDESC_GPUVMINSTPRINTER_H
#define LLVM_LIB_TARGET_GPUVM_MCTARGETDESC_GPUVMINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class GPUVMInstPrinter : public MCInstPrinter {
public:
  GPUVMInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                   const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;
  void printRegName(raw_ostream &O, MCRegister Reg) override;

  void printOperand(const MCInst *MI, unsigned OpNo,
                    const MCSubtargetInfo &STI, raw_ostream &O);
  void printBranchTarget(const MCInst *MI, uint64_t Address, unsigned OpNo,
                         const MCSubtargetInfo &STI, raw_ostream &O);
  void printFImm(const MCInst *MI, unsigned OpNo, const MCSubtargetInfo &STI,
                 raw_ostream &O);
  void printSR(const MCInst *MI, unsigned OpNo, const MCSubtargetInfo &STI,
               raw_ostream &O);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address,
                        const MCSubtargetInfo &STI, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address,
                       const MCSubtargetInfo &STI, raw_ostream &O);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               const MCSubtargetInfo &STI, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx);

  // The names of the special registers, by number (isa.h, GVM_SR_*).
  static const char *getSRName(unsigned N);

private:
  void printOne(const MCInst *MI, uint64_t Address,
                const MCSubtargetInfo &STI, raw_ostream &O);
};
} // namespace llvm

#endif
